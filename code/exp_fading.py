"""Physical channel outside the finite-order class: Rayleigh fading with Jakes (Clarke) Doppler
spectrum, generated by the IDFT method of Young & Beaulieu (IEEE TCOM 2000). A packet is lost
when |h|^2 falls below the threshold that gives loss rate eps. On long traces we compare the
trace-driven risk (sliding mission windows) with the predictions of order-L Markov fits
estimated from the same trace (keys M1-M6 hold L = 1, 2, 3, 4, 6; L = 1 is the Gilbert fit that pi_L is designed on), and with
the range [R^-, R^+] of the M = 2 compatible class of the Gilbert fit.
Run with argument "shadow" for composite fading: the Rayleigh power is multiplied by a log-normal
shadowing term whose dB value is a Gauss-Markov process (std 6 dB, correlation time 200 slots);
the threshold is then the empirical eps-quantile of the received power."""
import json, sys, time
import numpy as np
from scipy.signal import lfilter
from core import words, chain_from_p, box_ranges, box_chain, risk_dense, risk_schedule, periodic_slots
from policy import design_pi_L, evaluate_policy

T, B, ETA = 60, 15, 1e-4
NLOG2, NTRACES = 23, 4
rng = np.random.default_rng(2026)


def jakes_trace(fd, N):
    """Unit-power complex Gaussian process with Clarke autocorrelation J0(2 pi fd tau)."""
    km = int(np.floor(fd * N))
    k = np.arange(N)
    F = np.zeros(N)
    inner = (k >= 1) & (k <= km - 1)
    F[inner] = np.sqrt(1 / (2 * np.sqrt(1 - (k[inner] / (N * fd)) ** 2)))
    F[km] = np.sqrt(km / 2 * (np.pi / 2 - np.arctan((km - 1) / np.sqrt(2 * km - 1))))
    F[N - km] = F[km]
    outer = (k >= N - km + 1)
    F[outer] = np.sqrt(1 / (2 * np.sqrt(1 - ((N - k[outer]) / (N * fd)) ** 2)))
    h = np.fft.ifft(F * (rng.standard_normal(N) + 1j * rng.standard_normal(N)))
    return h / np.sqrt(np.mean(np.abs(h) ** 2))


def shadowing_db(N, std_db, corr):
    a = np.exp(-1 / corr)
    x0 = rng.standard_normal()
    x = lfilter([np.sqrt(1 - a * a)], [1, -a], rng.standard_normal(N), zi=[a * x0])[0]
    return std_db * x


def traces(eps, fd, shadow=None):
    pw = []
    for _ in range(NTRACES):
        p = np.abs(jakes_trace(fd, 2 ** NLOG2)) ** 2
        if shadow:
            p = p * 10 ** (shadowing_db(len(p), *shadow) / 10)
        pw.append(p)
    thr = -np.log(1 - eps) if not shadow else np.quantile(np.concatenate(pw), eps)
    return [(p >= thr).astype(np.int8) for p in pw]


def run_profile(trs, g, jmax):
    """Empirical run persistences rho^{(g)}_j of the g-decimated trace, j = 1..jmax."""
    P = []
    for j in range(1, jmax + 2):
        num = den = 0
        for gam in trs:
            for ph in range(g):
                x = (gam[ph::g] == 0).astype(np.int32)
                cs = np.concatenate(([0], np.cumsum(x)))
                num += np.count_nonzero(cs[j:] - cs[:-j] == j); den += len(x) - j + 1
        P.append(num / den)
    return [P[j] / P[j - 1] if P[j - 1] > 0 else float("nan") for j in range(1, jmax + 1)]


def fit_order(trs, M):
    """Markov fit of order M (the fitted order, L in the paper): (M+1)-block frequencies with a 0.5 pseudo-count."""
    cnt = np.zeros(2 ** (M + 1))
    for g in trs:
        idx = np.zeros(len(g) - M, dtype=np.int64)
        for i in range(M + 1):
            idx = 2 * idx + g[i:len(g) - M + i]
        cnt += np.bincount(idx, minlength=2 ** (M + 1))
    cnt += 0.5
    p = {}
    for w in words(M):
        base = int("".join(map(str, w)), 2) if M else 0
        p[w] = cnt[2 * base + 1] / (cnt[2 * base] + cnt[2 * base + 1])
    return chain_from_p(M, p)


def policy_array(table, D):
    A = np.zeros((T + 2, D + 1, B + 1, 3, T + 2), dtype=np.int8)
    for (t, d, r, o, k), u in table.items():
        if u: A[t, d, r, 2 if o is None else o, k] = 1
    return A


def trace_risk(trs, D, mode, pol=None, g=2):
    """Fraction of mission windows (start every 3 slots) that fail; mode: dense, periodic, policy."""
    fails = tot = 0
    for gam in trs:
        starts = np.arange(0, len(gam) - T, 3)
        N = len(starts)
        d = np.zeros(N, np.int64); r = np.full(N, B); o = np.full(N, 2); k = np.zeros(N, np.int64)
        failed = np.zeros(N, bool)
        for t in range(1, T + 1):
            x = gam[starts + t - 1]
            if mode == "dense": u = np.ones(N, bool)
            elif mode == "periodic": u = np.full(N, t % g == 0)
            else: u = (r > 0) & (pol[t, np.minimum(d, D), r, o, k] == 1)
            succ = u & (x == 1)
            d = np.where(succ, 0, d + 1)
            failed |= d >= D
            k = np.where(u, 1, np.where(o == 2, 0, k + 1)); o = np.where(u, x, o); r = np.where(u, r - 1, r)
        fails += failed.sum(); tot += N
    return fails / tot


SHADOW = len(sys.argv) > 1 and sys.argv[1] == "shadow"
CONFIGS = ([(0.05, 0.03, [10, 14, 18]), (0.01, 0.03, [8, 12, 16])] if SHADOW else
           [(0.05, 0.01, [12, 16, 20]), (0.05, 0.03, [6, 8, 10]), (0.01, 0.005, [8, 11, 14])])
out = []
t0 = time.time()
for eps, fd, Ds in CONFIGS:
    trs = traces(eps, fd, (6.0, 200.0) if SHADOW else None)
    fits = {M: fit_order(trs, M) for M in (1, 2, 3, 4, 6)}
    c = fits[1].marginal(2)
    q0, q1 = fits[1].p[(0,)], fits[1].p[(1,)]
    R = box_ranges(c, 1, ETA)
    cls = [box_chain(c, 1, {(0,): a, (1,): b}) for a in np.linspace(*R[(0,)], 41) for b in np.linspace(*R[(1,)], 5)]
    prof = {"dense": run_profile(trs, 1, 20), "dec2": run_profile(trs, 2, 10)}
    print("  run persistence dense:", np.round(prof["dense"], 3), "| 2-decimated:", np.round(prof["dec2"], 3))
    print(f"eps={eps} fd={fd}: loss rate {1 - fits[1].mu[(1,)]:.4f}, mean burst {1 / q0:.2f}, "
          f"P(0|00)={1 - fits[2].p[(0, 0)]:.3f}, P(0|01)={1 - fits[2].p[(0, 1)]:.3f}  [{time.time() - t0:.0f}s]", flush=True)
    for D in Ds:
        tab, _ = design_pi_L(q0, q1, T, D, B)
        pol = policy_array(tab, D)
        row = dict(eps=eps, fd=fd, D=D, loss=1 - fits[1].mu[(1,)], mean_burst=1 / q0, profile=prof,
                   p0_00=1 - fits[2].p[(0, 0)], p0_01=1 - fits[2].p[(0, 1)])
        for name, ev in (("dense", lambda ch: risk_dense(ch, T, D)),
                         ("periodic2", lambda ch: risk_schedule(ch, T, D, periodic_slots(T, 2))),
                         ("piL_B15", lambda ch: evaluate_policy(ch, tab, T, D, B)[0])):
            mode = {"dense": "dense", "periodic2": "periodic", "piL_B15": "policy"}[name]
            truth = trace_risk(trs, D, mode, pol)
            pred = {f"M{M}": float(ev(ch)) for M, ch in fits.items()}
            vals = [float(ev(ch)) for ch in cls]
            row[name] = dict(truth=float(truth), **pred, class_min=min(vals), class_max=max(vals))
            print(f"  D={D:2d} {name:9s} truth={truth:.3e} | " + " ".join(f"{k}={v:.2e}" for k, v in pred.items())
                  + f" | M2-class [{min(vals):.2e}, {max(vals):.2e}]  [{time.time() - t0:.0f}s]", flush=True)
        out.append(row)
json.dump(dict(T=T, B=B, eta=ETA, trace_len=NTRACES * 2 ** NLOG2, shadow=[6.0, 200.0] if SHADOW else None, rows=out),
          open("results/fading_shadow.json" if SHADOW else "results/fading.json", "w"), indent=1)
